package main

import (
	"bufio"
	"fmt"
	"hash/fnv"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type constParseStats struct {
	Files     int
	Lines     int
	Emitted   int
	Dropped   int
	Duplicate int
	Warnings  int
}

type constRow struct {
	name   string
	symbol string
	value  int64
	source string
}

type constParseResult struct {
	rows     []constRow
	stats    constParseStats
	warnings []string
}

func (w *writer) emitConstsFile() error {
	root := w.syzkallerRoot
	if root == "" {
		root = "."
	}
	result, err := parseAllConsts(root, w.target.OS, w.target.Arch)
	if err != nil {
		return err
	}
	w.constStats = result.stats

	path := filepath.Join(w.constsOutDir, "consts.gen.hpp")
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	p := func(format string, args ...interface{}) {
		fmt.Fprintf(f, format, args...)
	}
	p("// AUTO-GENERATED by tools/syzgen - DO NOT EDIT\n")
	p("// Target: %s/%s\n", w.target.OS, w.target.Arch)
	p("// Role: ODR-safe inline constexpr constants; may be included directly\n")
	p("// Source: syzkaller/sys/%s/*.const\n", w.target.OS)
	p("#pragma once\n\n")
	p("#include <cstdint>\n\n")
	p("namespace refuzz::fuzzer::syz::consts {\n\n")
	p("// ---- syzkaller named constants ----------------------------------\n")
	for _, row := range result.rows {
		p("inline constexpr int64_t %s = %s; // %s\n",
			row.symbol, intLiteral(row.value), cppComment(row.name))
	}
	p("\ninline constexpr uint32_t kSyzConstCount = %du;\n", uint32(len(result.rows)))
	p("static_assert(kSyzConstCount == %du, \"generated const size mismatch\");\n\n", uint32(len(result.rows)))
	p("} // namespace refuzz::fuzzer::syz::consts\n")
	return nil
}

func parseAllConsts(root string, osName string, arch string) (constParseResult, error) {
	if osName == "" {
		osName = "linux"
	}
	pattern := filepath.Join(root, "sys", osName, "*.const")
	paths, err := filepath.Glob(pattern)
	if err != nil {
		return constParseResult{}, err
	}
	if len(paths) == 0 {
		return constParseResult{}, fmt.Errorf("no const files match %s", pattern)
	}
	sort.Strings(paths)

	byName := make(map[string]constRow)
	var result constParseResult
	for _, path := range paths {
		if err := parseConstFile(path, arch, byName, &result); err != nil {
			return constParseResult{}, err
		}
	}

	result.rows = make([]constRow, 0, len(byName))
	for _, row := range byName {
		result.rows = append(result.rows, row)
	}
	sort.Slice(result.rows, func(i, j int) bool {
		return result.rows[i].name < result.rows[j].name
	})
	assignConstSymbols(result.rows)
	result.stats.Emitted = len(result.rows)
	result.stats.Warnings = len(result.warnings)
	return result, nil
}

func parseConstFile(path string, arch string, byName map[string]constRow, result *constParseResult) error {
	if !constPathSupportsArch(path, arch) {
		return nil
	}
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()

	result.stats.Files++
	scanner := bufio.NewScanner(f)
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		raw := scanner.Text()
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if isArchesLine(line) {
			if !constFileSupportsArch(line, arch) {
				return nil
			}
			continue
		}
		result.stats.Lines++
		name, value, ok, recognized, err := parseConstLine(line, arch)
		if err != nil {
			return fmt.Errorf("%s:%d: %w", path, lineNo, err)
		}
		if !recognized {
			result.warnings = append(result.warnings, fmt.Sprintf("%s:%d: %s", path, lineNo, line))
			continue
		}
		if name == "" {
			continue
		}
		if !ok {
			result.stats.Dropped++
			continue
		}
		source := fmt.Sprintf("%s:%d", path, lineNo)
		row := constRow{name: name, value: value, source: source}
		if old, exists := byName[name]; exists {
			if old.value != value {
				return fmt.Errorf("%s conflicts: %s has %d, %s has %d",
					name, old.source, old.value, source, value)
			}
			result.stats.Duplicate++
			continue
		}
		byName[name] = row
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	return nil
}

var constArchSuffixes = []string{
	"386",
	"amd64",
	"arm",
	"arm64",
	"mips64le",
	"ppc64le",
	"riscv64",
	"s390x",
}

func constPathSupportsArch(path string, arch string) bool {
	base := filepath.Base(path)
	stem := strings.TrimSuffix(base, ".const")
	for _, suffix := range constArchSuffixes {
		if strings.HasSuffix(stem, "_"+suffix) {
			return suffix == arch
		}
	}
	return true
}

func isArchesLine(line string) bool {
	lhs, _, found := strings.Cut(line, "=")
	return found && strings.TrimSpace(lhs) == "arches"
}

func constFileSupportsArch(line string, arch string) bool {
	_, rhs, found := strings.Cut(line, "=")
	if !found {
		return true
	}
	for _, part := range strings.Split(rhs, ",") {
		if strings.TrimSpace(part) == arch {
			return true
		}
	}
	return false
}

func parseConstLine(line string, arch string) (name string, value int64, ok bool, recognized bool, err error) {
	lhs, rhs, found := strings.Cut(line, "=")
	if !found {
		return "", 0, false, false, nil
	}
	name = strings.TrimSpace(lhs)
	rhs = strings.TrimSpace(rhs)
	if name == "" || rhs == "" {
		return "", 0, false, false, nil
	}
	if name == "arches" {
		return "", 0, false, true, nil
	}

	token, selected := selectConstValueToken(rhs, arch)
	if !selected {
		return name, 0, false, true, nil
	}
	if token == "???" {
		return name, 0, false, true, nil
	}
	value, err = parseConstInt64(token)
	if err != nil {
		return "", 0, false, false, nil
	}
	return name, value, true, true, nil
}

func selectConstValueToken(rhs string, arch string) (string, bool) {
	var defaultToken string
	defaultSet := false
	var archToken string
	archSet := false

	for _, raw := range strings.Split(rhs, ",") {
		seg := strings.TrimSpace(raw)
		if seg == "" {
			continue
		}
		parts := strings.Split(seg, ":")
		if len(parts) == 1 {
			defaultToken = strings.TrimSpace(parts[0])
			defaultSet = true
			continue
		}
		valueToken := strings.TrimSpace(parts[len(parts)-1])
		for _, archPart := range parts[:len(parts)-1] {
			if strings.TrimSpace(archPart) == arch {
				archToken = valueToken
				archSet = true
				break
			}
		}
	}
	if archSet {
		return archToken, true
	}
	if defaultSet {
		return defaultToken, true
	}
	return "", false
}

func parseConstInt64(s string) (int64, error) {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "-") {
		return strconv.ParseInt(s, 0, 64)
	}
	v, err := strconv.ParseUint(s, 0, 64)
	if err != nil {
		return 0, err
	}
	return int64(v), nil
}

func assignConstSymbols(rows []constRow) {
	used := make(map[string]struct{}, len(rows))
	for i := range rows {
		name := strings.TrimLeft(rows[i].name, "_")
		if name == "" {
			name = rows[i].name
		}
		base := "kSyzConst_" + sanitizeIdent(name)
		symbol := base
		if _, exists := used[symbol]; exists {
			hash := fnv.New32a()
			_, _ = hash.Write([]byte(rows[i].name))
			symbol = fmt.Sprintf("%s_%06x", base, hash.Sum32()&0xffffff)
		}
		for {
			if _, exists := used[symbol]; !exists {
				break
			}
			hash := fnv.New32a()
			_, _ = hash.Write([]byte(fmt.Sprintf("%s:%d", rows[i].name, i)))
			symbol = fmt.Sprintf("%s_%06x_%d", base, hash.Sum32()&0xffffff, i)
		}
		used[symbol] = struct{}{}
		rows[i].symbol = symbol
	}
}
