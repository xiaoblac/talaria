const std::vector<AlgDesc>& algs_for(AlgKind k) {
    switch (k) {
        case AlgKind::kCipher:   return kAlgsCipher;
        case AlgKind::kSkcipher: return kAlgsSkcipher;
        case AlgKind::kAead:     return kAlgsAead;
        case AlgKind::kHash:     return kAlgsHash;
        case AlgKind::kRng:      return kAlgsRng;
    }
    return kAlgsCipher;
}

