RequiredFeatures analyze_required_features(const syz::Prog& prog) {
    RequiredFeatures f;
    for (const auto& call : prog.calls()) {
        if (call == nullptr) continue;
        syz::foreach_arg(const_cast<syz::Call*>(call.get()),
                         [&](syz::Arg* a, syz::ArgCtx*) {
            if (a == nullptr) return;
            const auto* t = a->type();
            if (t == nullptr) return;
            if (a->arg_kind() == syz::ArgKind::kConst) {
                if (t->bitfield_offset() != 0 || t->bitfield_length() != 0) {
                    f.bitmasks = true;
                }
            }
            if (t->kind() == syz::TypeKind::kCsum) {
                f.csums = true;
            }
        });
        const auto& props = call->props();
        if (props.fail_nth > 0) f.fault_injection = true;
        if (props.async)        f.async = true;
    }
    return f;
}

std::vector<std::string> common_defines(
    const syz::Prog& /*prog*/, const Options& opts,
    const ICSourceTargetInfo& target_info,
    const RequiredFeatures& features) {
    // Mirror common.go::commonDefines (91-131). Each entry maps a
    // SYZ_* / GOOS_* / etc. flag to a bool; we emit "<name>=1" for
    // true values (cpp's `-D NAME` defaults to 1, but using "=1"
    // matches upstream removeSystemDefines's `=1` strip pattern).
    struct NamedBool { std::string_view name; bool value; };
    const std::string goos = std::string(target_info.goos());
    const std::string goarch = std::string(target_info.goarch());
    const std::string host = std::string(target_info.host_goos());
    const std::string goos_def    = std::format("GOOS_{}", goos);
    const std::string goarch_def  = std::format("GOARCH_{}", goarch);
    const std::string hostgoos_def = std::format("HOSTGOOS_{}", host);

    const std::string sandbox = opts.Sandbox;
    const NamedBool flags[] = {
        {goos_def,                    true},
        {goarch_def,                  true},
        {hostgoos_def,                true},
        {"SYZ_USE_BITMASKS",          features.bitmasks},
        {"SYZ_USE_CHECKSUMS",         features.csums},
        {"SYZ_SANDBOX_NONE",          sandbox == "none"},
        {"SYZ_SANDBOX_SETUID",        sandbox == "setuid"},
        {"SYZ_SANDBOX_NAMESPACE",     sandbox == "namespace"},
        {"SYZ_SANDBOX_ANDROID",       sandbox == "android"},
        {"SYZ_THREADED",              opts.Threaded},
        {"SYZ_ASYNC",                 features.async},
        {"SYZ_REPEAT",                opts.Repeat},
        {"SYZ_REPEAT_TIMES",          opts.RepeatTimes > 1},
        {"SYZ_MULTI_PROC",            opts.Procs > 1},
        {"SYZ_FAULT",                 features.fault_injection},
        {"SYZ_LEAK",                  opts.Leak},
        {"SYZ_NET_INJECTION",         opts.NetInjection},
        {"SYZ_NET_DEVICES",           opts.NetDevices},
        {"SYZ_NET_RESET",             opts.NetReset},
        {"SYZ_CGROUPS",               opts.Cgroups},
        {"SYZ_BINFMT_MISC",           opts.BinfmtMisc},
        {"SYZ_CLOSE_FDS",             opts.CloseFDs},
        {"SYZ_KCSAN",                 opts.KCSAN},
        {"SYZ_DEVLINK_PCI",           opts.DevlinkPCI},
        {"SYZ_NIC_VF",                opts.NicVF},
        {"SYZ_USB",                   opts.USB},
        {"SYZ_VHCI_INJECTION",        opts.VhciInjection},
        {"SYZ_USE_TMP_DIR",           opts.UseTmpDir},
        {"SYZ_HANDLE_SEGV",           opts.HandleSegv},
        {"SYZ_TRACE",                 opts.Trace},
        {"SYZ_WIFI",                  opts.Wifi},
        {"SYZ_802154",                opts.IEEE802154},
        {"SYZ_SYSCTL",                opts.Sysctl},
        {"SYZ_SWAP",                  opts.Swap},
        {"SYZ_EXECUTOR_USES_FORK_SERVER", target_info.executor_uses_fork_server()},
    };
    std::vector<std::string> out;
    out.reserve(40);
    for (const auto& f : flags) {
        if (f.value) out.emplace_back(f.name);
    }
    return out;
}

std::vector<std::string> define_list(
    const syz::Prog& prog, const syz::Prog& mmap_prog,
    const Options& opts, const ICSourceTargetInfo& target_info,
    const RequiredFeatures& features) {
    std::set<std::string> uniq;
    for (auto& d : common_defines(prog, opts, target_info, features)) {
        uniq.insert(std::move(d));
    }
    auto add_per_call = [&](const syz::Prog& p) {
        for (const auto& c : p.calls()) {
            if (c == nullptr || c->meta() == nullptr) continue;
            uniq.insert(std::string("__NR_") + c->meta()->call_name());
        }
    };
    add_per_call(prog);
    add_per_call(mmap_prog);
    std::vector<std::string> out(uniq.begin(), uniq.end());
    std::sort(out.begin(), out.end());
    return out;
}

std::string remove_system_defines(std::string src,
                                  const std::vector<std::string>& defines) {
    // Mirror common.go::removeSystemDefines (133-167).
    std::unordered_map<std::string, std::string> remove = {
        {"__STDC__",                 "1"},
        {"__STDC_HOSTED__",          "1"},
        {"__STDC_UTF_16__",          "1"},
        {"__STDC_UTF_32__",          "1"},
        {"__STDC_EMBED_NOT_FOUND__", "0"},
        {"__STDC_EMBED_FOUND__",     "1"},
        {"__STDC_EMBED_EMPTY__",     "2"},
    };
    for (const auto& d : defines) {
        const auto eq = d.find('=');
        if (eq == std::string::npos) {
            remove[d] = "1";
        } else {
            remove[d.substr(0, eq)] = d.substr(eq + 1);
        }
    }
    std::string out;
    out.reserve(src.size());
    out.swap(src);
    for (const auto& [name, val] : remove) {
        std::string needle = std::format("#define {} {}\n", name, val);
        for (;;) {
            auto pos = out.find(needle);
            if (pos == std::string::npos) break;
            out.erase(pos, needle.size());
        }
    }
    // Strip "#define __STDC_VERSION__ <anything>\n" — upstream does the
    // same in a regex-like loop (common.go:154-165).
    {
        const std::string prefix = "#define __STDC_VERSION__";
        for (;;) {
            auto pos = out.find(prefix);
            if (pos == std::string::npos) break;
            auto eol = out.find('\n', pos);
            if (eol == std::string::npos) break;
            out.erase(pos, eol - pos + 1);
        }
    }
    return out;
}

std::expected<std::string, CSourceFailure>
create_common_header(
    const syz::Prog& prog, const syz::Prog& mmap_prog,
    const std::unordered_map<std::string, std::string>& replacements,
    const Options& opts, const ICSourceTargetInfo& target_info,
    const RequiredFeatures& features) {
    auto defines = define_list(prog, mmap_prog, opts, target_info, features);

    std::vector<std::string_view> argv;
    argv.reserve(11 + defines.size());
    argv.emplace_back(target_info.cpp_path());
    argv.emplace_back("-nostdinc");
    argv.emplace_back("-undef");
    argv.emplace_back("-fdirectives-only");
    argv.emplace_back("-dDI");
    argv.emplace_back("-E");
    argv.emplace_back("-P");
    argv.emplace_back("-CC");
    argv.emplace_back("-");
    std::vector<std::string> d_flags;
    d_flags.reserve(defines.size());
    for (const auto& d : defines) {
        d_flags.push_back("-D" + d);
    }
    for (const auto& d : d_flags) argv.emplace_back(d);

    // 600s wall budget. A normal cs::Write returns cpp output in well
    // under 1s (the embedded common header is 580KB; cpp prunes #if
    // blocks and dumps directives via -dDI). Empirically the heaviest
    // mount-image progs (`syz_mount_image_gfs2_*`) take ~10s wall at
    // jobs=6; the very heaviest (`syz_mount_image_ext4_28/29`) blew
    // a 300s budget under contention. The generous 600s ceiling
    // absorbs that without giving up the fail-fast signal — if a
    // prog needs > 600s of cpp work, that's not contention, it's a
    // legitimate `-D` set explosion worth investigating per Epic 4
    // plan §8 stop condition. Production fuzz callers see no
    // behavioral change because cpp on a sane prog is sub-second.
    auto run = run_process(argv, ::refuzz::crash::repro::csource::kCsourceCommonSource,
                           std::chrono::seconds(600));
    if (!run.has_value()) {
        return std::unexpected(cpp_failed(std::format(
            "spawn cpp failed: {}", run.error())));
    }
    // PR-4-B-rev3 fix: even when cpp produced partial stdout, a
    // timed_out run is structurally incomplete — the post-replace
    // step would build a half-substituted header and ship it as a
    // .c reproducer that compiles to garbage. Treat timeout as a
    // hard fail regardless of stdout content. Mirror upstream's
    // "ignore exit code" rule (common.go:42-49) only for the
    // "non-zero exit but full stdout" case.
    if (run->timed_out) {
        return std::unexpected(cpp_failed(std::format(
            "cpp timed out (stdout {} bytes, stderr first 200B: {})",
            run->stdout_.size(), run->stderr_.substr(0, 200))));
    }
    if (run->stdout_.empty()) {
        return std::unexpected(cpp_failed(std::format(
            "cpp produced empty stdout (exit={}, stderr first 200B: {})",
            run->exit_code, run->stderr_.substr(0, 200))));
    }

    std::string src = remove_system_defines(std::move(run->stdout_), defines);

    for (const auto& [from, to] : replacements) {
        const std::string marker = "/*{{{" + from + "}}}*/";
        for (;;) {
            auto pos = src.find(marker);
            if (pos == std::string::npos) break;
            src.replace(pos, marker.size(), to);
        }
    }

    // uintNN → uintNN_t.
    for (const auto& [from, to] : std::vector<std::pair<std::string, std::string>>{
             {"uint64", "uint64_t"},
             {"uint32", "uint32_t"},
             {"uint16", "uint16_t"},
             {"uint8",  "uint8_t"},
         }) {
        for (std::size_t pos = 0;; ) {
            auto p = src.find(from, pos);
            if (p == std::string::npos) break;
            src.replace(p, from.size(), to);
            pos = p + to.size();
        }
    }

    // Strip "#define SYZ_HAVE_.*" lines.
    {
        std::regex re("#define SYZ_HAVE_[^\n]*");
        src = std::regex_replace(src, re, "");
    }
    return src;
}

